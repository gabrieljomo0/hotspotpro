"use client";

// The headline numbers for one agent: how many vouchers they hold, how many
// are sold, what that is worth, and what they've sold today / this week /
// this month.

import { sym } from "@/components/dashboard/shared/currency";
import { CalendarDays, CheckCircle2, Clock, CreditCard, Banknote, Ticket } from "lucide-react";

import type { AgentStats } from "../agentLedger";

function money(value: number) {
  return `${sym()} ${value.toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
}

function Card({
  id,
  label,
  value,
  hint,
  hintClass,
  icon,
}: {
  id: string;
  label: string;
  value: string;
  hint: string;
  hintClass: string;
  icon: React.ReactNode;
}) {
  return (
    <div data-testid={id} className="rounded-2xl border border-[#e2e8f0] bg-white p-5">
      <p className="text-sm text-[#64748b]">{label}</p>
      <p className="mt-1 text-3xl font-black text-[#0f172a]">{value}</p>
      <p className={`mt-2 flex items-center gap-1.5 text-xs font-semibold ${hintClass}`}>
        <span>{hint}</span>
        {icon}
      </p>
    </div>
  );
}

export function AgentStatCards({ stats }: { stats: AgentStats }) {
  return (
    <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-4" data-testid="agent-stat-cards">
      <Card id="stat-given" label="Total Given" value={String(stats.totalGiven)} hint="Given by you or generated by the agent" hintClass="text-emerald-600" icon={<Ticket size={12} />} />
      <Card id="stat-sold" label="Total Sold" value={String(stats.totalSold)} hint={`${stats.sellThroughPercent}% sell-through rate`} hintClass="text-emerald-600" icon={<CheckCircle2 size={12} />} />
      <Card
        id="stat-remaining"
        label="Remaining"
        value={String(stats.remaining)}
        hint={stats.expired > 0 ? `Available for sale · ${stats.expired} expired` : "Available for sale"}
        hintClass="text-amber-600"
        icon={<Clock size={12} />}
      />
      <Card id="stat-retail" label="Retail Sales Value" value={money(stats.retailSalesValue)} hint="Face value of redeemed vouchers" hintClass="text-emerald-600" icon={<Banknote size={12} />} />
      <Card id="stat-prepaid" label="Prepaid Payments" value={money(stats.prepaidPayments)} hint="Paid from their wallet when generating" hintClass="text-emerald-600" icon={<CreditCard size={12} />} />
      <Card id="stat-today" label="Sold Today" value={String(stats.soldToday.count)} hint={`${money(stats.soldToday.value)} retail value`} hintClass="text-[#2563eb]" icon={<CalendarDays size={12} />} />
      <Card id="stat-week" label="Sold This Week" value={String(stats.soldThisWeek.count)} hint={`${money(stats.soldThisWeek.value)} retail value`} hintClass="text-[#2563eb]" icon={<CalendarDays size={12} />} />
      <Card id="stat-month" label="Sold This Month" value={String(stats.soldThisMonth.count)} hint={`${money(stats.soldThisMonth.value)} retail value`} hintClass="text-[#2563eb]" icon={<CalendarDays size={12} />} />
    </div>
  );
}
