// Writes src/http/routeTable.ts: one import per route file under src/routes/api,
// with its URL pattern ([name] folders are URL parameters).
// Run after adding or removing a route file:  npm run routes
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const routesDir = path.join(root, "src", "routes");
const found = [];

(function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full);
    else if (entry.name === "route.ts") found.push(path.relative(routesDir, path.dirname(full)).split(path.sep));
  }
})(routesDir);

// More specific first: at the first difference, a fixed word beats a [parameter].
const isParam = (s) => /^\[.+\]$/.test(s);
found.sort((a, b) => {
  for (let i = 0; i < Math.max(a.length, b.length); i += 1) {
    if (a[i] === undefined) return 1;
    if (b[i] === undefined) return -1;
    if (isParam(a[i]) !== isParam(b[i])) return isParam(a[i]) ? 1 : -1;
  }
  return b.length - a.length || a.join("/").localeCompare(b.join("/"));
});

// Extra public addresses for a route (the Payments screen shows /webhooks/hubtel).
const aliases = { "api/webhooks/hubtel": ["webhooks/hubtel"] };

let out = `// GENERATED by scripts/gen-routes.mjs — do not edit by hand. Run: npm run routes\nimport type { RouteModule } from "./adapter";\n\n`;
found.forEach((segments, i) => {
  out += `import * as r${i} from "../routes/${segments.join("/")}/route";\n`;
});
out += `\nexport type RouteEntry = { pattern: string; segments: string[]; module: RouteModule };\n\nexport const routeTable: RouteEntry[] = [\n`;
found.forEach((segments, i) => {
  const urls = [segments.join("/"), ...(aliases[segments.join("/")] ?? [])];
  for (const url of urls) {
    const parts = url.split("/").map((s) => (isParam(s) ? `:${s.slice(1, -1)}` : s));
    out += `  { pattern: "/${parts.join("/")}", segments: ${JSON.stringify(parts)}, module: r${i} as unknown as RouteModule },\n`;
  }
});
out += `];\n`;
fs.writeFileSync(path.join(root, "src", "http", "routeTable.ts"), out);
console.log(`Wrote ${found.length} routes to src/http/routeTable.ts`);
